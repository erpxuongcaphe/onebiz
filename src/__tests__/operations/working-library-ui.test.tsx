 if(url.startsWith('/api/operations/people'))return{ok:true,json:async()=>({people:[{id:user,name:'Quản lý A'},{id:user2,name:'Quản lý B'}]})};
 if(init?.method==='POST')return{ok:true,json:async()=>({result:{}})};
