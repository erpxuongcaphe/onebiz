  libraries=[lib];render(<WorkingLibrary workspace={workspace} onApplied={vi.fn()}/>);
  fireEvent.click(await screen.findByRole('button',{name:'Áp dụng cho chi nhánh'}));
  fireEvent.click(screen.getByRole('checkbox',{name:'Quán A'}));
